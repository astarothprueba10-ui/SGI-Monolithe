CREATE TABLE IF NOT EXISTS public.ven_ventas_medios_pago (
 id_venta bigint PRIMARY KEY REFERENCES public.ven_ventas(id_venta),
 id_metodo_pago integer NOT NULL REFERENCES public.cfg_metodos_pago(id_metodo_pago),
 numero_operacion varchar(80),
 monto_pendiente_revision numeric(14,2) NOT NULL CHECK (monto_pendiente_revision>=0),
 tipo_abono varchar(15) NOT NULL CHECK(tipo_abono IN ('CONTADO','INICIAL')),
 estado_revision varchar(15) NOT NULL DEFAULT 'PENDIENTE'
   CHECK(estado_revision IN ('PENDIENTE','APROBADO','RECHAZADO')),
 id_usuario_registro bigint NOT NULL REFERENCES public.seg_usuarios(id_usuario),
 fecha_registro timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.ven_ventas_comprobantes (
 id_comprobante bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_venta bigint NOT NULL REFERENCES public.ven_ventas(id_venta),
 bucket varchar(80) NOT NULL DEFAULT 'vouchers-ventas-private'
   CHECK(bucket='vouchers-ventas-private'),
 clave_archivo text UNIQUE NOT NULL,
 nombre_archivo varchar(255) NOT NULL,
 tipo_mime varchar(50) NOT NULL
  CHECK(tipo_mime IN ('application/pdf','image/jpeg','image/png','image/webp')),
 tamanio_bytes bigint NOT NULL CHECK(tamanio_bytes>0 AND tamanio_bytes<=5242880),
 estado_revision varchar(15) NOT NULL DEFAULT 'PENDIENTE'
  CHECK (estado_revision IN ('PENDIENTE','APROBADO','RECHAZADO')),
 fecha_carga timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_ven_ventas_comprobantes_idventa
 ON public.ven_ventas_comprobantes(id_venta);
ALTER TABLE public.ven_ventas_medios_pago ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ven_ventas_comprobantes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.ven_ventas_medios_pago,public.ven_ventas_comprobantes
