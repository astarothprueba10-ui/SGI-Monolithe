-- Esquema MINIMO DE PRUEBAS, NO MIGRACION DE PRODUCCION.
-- Refleja las columnas JPA utilizadas por el publicador de 3E.2.
-- No incorpora las migraciones 32-36, que no se recibieron en el ZIP.
CREATE TABLE cms_paginas (
    id_pagina bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estado_publicacion int NOT NULL,
    codigo varchar(40) NOT NULL UNIQUE,
    slug varchar(150) NOT NULL UNIQUE,
    titulo varchar(180) NOT NULL,
    descripcion varchar(500),
    titulo_seo varchar(180),
    descripcion_seo varchar(320),
    orden int NOT NULL DEFAULT 0,
    mostrar_menu boolean NOT NULL DEFAULT true,
    fecha_publicacion timestamptz,
    id_usuario_registro bigint,
    id_usuario_publicacion bigint,
    activo boolean NOT NULL DEFAULT true,
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    fecha_actualizacion timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE cms_secciones (
    id_seccion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pagina bigint NOT NULL REFERENCES cms_paginas(id_pagina),
    id_tipo_seccion int NOT NULL,
    codigo varchar(50) NOT NULL,
    titulo varchar(180),
    subtitulo varchar(255),
    contenido text,
    configuracion jsonb,
    orden int NOT NULL DEFAULT 0,
    visible boolean NOT NULL DEFAULT true,
    fecha_desde timestamptz,
    fecha_hasta timestamptz,
    id_usuario_registro bigint,
    activo boolean NOT NULL DEFAULT true,
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    fecha_actualizacion timestamptz NOT NULL DEFAULT now(),
    UNIQUE (id_pagina, codigo)
);
CREATE TABLE cms_borradores (
    id_borrador bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_grupo_edicion uuid NOT NULL DEFAULT gen_random_uuid(),
    tipo_objetivo varchar(30) NOT NULL,
    id_pagina bigint REFERENCES cms_paginas(id_pagina),
    id_proyecto bigint,
    contenido_pendiente jsonb NOT NULL,
    revision_base bigint NOT NULL DEFAULT 0,
    revision_edicion bigint NOT NULL DEFAULT 1,
    estado varchar(20) NOT NULL DEFAULT 'EN_EDICION',
    id_usuario_registro bigint NOT NULL,
    id_usuario_publicacion bigint,
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    fecha_actualizacion timestamptz NOT NULL DEFAULT now(),
    fecha_publicacion timestamptz
);
CREATE TABLE cms_publicacion_versiones (
    id_version_publicacion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pagina bigint UNIQUE REFERENCES cms_paginas(id_pagina),
    id_proyecto bigint,
    revision bigint NOT NULL DEFAULT 0,
    fecha_actualizacion timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE cms_borrador_imagenes (
    id_imagen_borrador bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_borrador bigint NOT NULL REFERENCES cms_borradores(id_borrador),
    id_seccion bigint NOT NULL REFERENCES cms_secciones(id_seccion),
    bucket_id text NOT NULL,
    object_key text NOT NULL,
    mime_type varchar(30) NOT NULL,
    tamano_bytes bigint NOT NULL,
    hash_sha256 char(64) NOT NULL,
    id_usuario_registro bigint NOT NULL,
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    fecha_actualizacion timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE cms_publicacion_historial (
    id_historial bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pagina bigint NOT NULL REFERENCES cms_paginas(id_pagina),
    id_borrador bigint NOT NULL UNIQUE REFERENCES cms_borradores(id_borrador),
    id_usuario_publicacion bigint NOT NULL,
    revision_anterior bigint NOT NULL,
    revision_nueva bigint NOT NULL,
    snapshot_anterior jsonb NOT NULL,
    snapshot_nuevo jsonb NOT NULL,
    version_formato smallint NOT NULL DEFAULT 1,
    fecha_publicacion timestamptz NOT NULL DEFAULT now(),
    UNIQUE (id_pagina, revision_nueva),
    -- Solo en este esquema QA: simula un INSERT fallido al registrar historial.
    CONSTRAINT qa_forzar_fallo_historial CHECK (id_usuario_publicacion <> 9002)
);
