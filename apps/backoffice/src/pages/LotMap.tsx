function getPolygonColors(codigoEstadoLote?: string | null) {
  const found = REAL_STATUSES.find((s) => s.code === codigoEstadoLote);
  if (found) {
    return { fill: found.polygonFill, stroke: found.polygonStroke };
  }
  return { fill: '#9ca3af', stroke: '#4b5563' };
}

function naturalCompare(a?: string | null, b?: string | null): number {
  const strA = (a ?? '').trim();
  const strB = (b ?? '').trim();
  return strA.localeCompare(strB, undefined, { numeric: true, sensitivity: 'base' });
}

function buildDisplayGeometries(
  lots: LoteResponse[],
  planDetail: PlanoInteractivoDetalleResponse | null,
  selectedProjectId: number | null
): DisplayGeometria[] {
  if (lots.length === 0) return [];

  const persistedMap = new Map<number, LoteGeometriaResponse>();
  if (planDetail?.lotes) {
    planDetail.lotes.forEach((g) => {
      if (g.activo) {
        persistedMap.set(g.idLote, g);
      }
    });
  }

  const resultGeometries: DisplayGeometria[] = [];
  const unpositionedLots: LoteResponse[] = [];

  lots.forEach((lote) => {
    const persisted = persistedMap.get(lote.idLote);
    if (persisted) {
      resultGeometries.push({
        ...persisted,
        isAutoGenerated: false
      });
    } else {
      unpositionedLots.push(lote);
    }
  });

  if (unpositionedLots.length === 0) {
    return resultGeometries;
  }

  const lotWidth = 68;
  const lotHeight = 55;
  const gapX = 12;
  const rowHeight = 80;
  const stageGap = 35;

  // Si no hay ninguna geometría persistida previa: auto-layout completo de unpositionedLots
  if (resultGeometries.length === 0) {
    type StageGroup = {
      key: string;
      nombre: string;
      manzanas: Map<string, LoteResponse[]>;
    };

    const stagesMap = new Map<string, StageGroup>();

    unpositionedLots.forEach((lote) => {
      const stageKey = String(lote.idEtapa ?? lote.nombreEtapa ?? lote.codigoEtapa ?? 'etapa-default');
      const stageName = lote.nombreEtapa || lote.codigoEtapa || 'Etapa Principal';

      if (!stagesMap.has(stageKey)) {
        stagesMap.set(stageKey, {
          key: stageKey,
          nombre: stageName,
          manzanas: new Map<string, LoteResponse[]>()
        });
      }

      const stageObj = stagesMap.get(stageKey)!;
      const blockKey = lote.nombreManzana || lote.codigoManzana || 'Manzana Unica';

      const blockList = stageObj.manzanas.get(blockKey) ?? [];
      blockList.push(lote);
      stageObj.manzanas.set(blockKey, blockList);
    });

    const sortedStages = Array.from(stagesMap.values()).sort((a, b) =>
      naturalCompare(a.nombre, b.nombre)
    );

    let maxLotsInRow = 1;
    sortedStages.forEach((stg) => {
      stg.manzanas.forEach((mLots) => {
        if (mLots.length > maxLotsInRow) {
          maxLotsInRow = mLots.length;
        }
      });
    });

    const maxRowWidth = maxLotsInRow * lotWidth + (maxLotsInRow - 1) * gapX;
    const usableAreaWidth = Math.max(740, maxRowWidth);

    let currentY = 50;

    sortedStages.forEach((stg) => {
      const sortedBlocks = Array.from(stg.manzanas.entries()).sort(([bKeyA], [bKeyB]) =>
        naturalCompare(bKeyA, bKeyB)
      );

      sortedBlocks.forEach(([_bKey, mLots]) => {
        mLots.sort((lA, lB) => naturalCompare(lA.numero || lA.codigo, lB.numero || lB.codigo));

        const count = mLots.length;
        const rowWidth = count * lotWidth + (count - 1) * gapX;
        const startX = 115 + Math.max(0, Math.floor((usableAreaWidth - rowWidth) / 2));

        mLots.forEach((lote, idx) => {
          const x = startX + idx * (lotWidth + gapX);
          const y = currentY;

          resultGeometries.push({
            idLoteGeometria: -(lote.idLote),
            idProyecto: lote.idProyecto ?? selectedProjectId ?? 0,
            idPlanoInteractivo: planDetail?.plano.idPlanoInteractivo ?? 0,
            idLote: lote.idLote,
            codigoLote: lote.codigo,
            numeroLote: lote.numero,
            puntos: [
              { x, y },
              { x: x + lotWidth, y },
              { x: x + lotWidth, y: y + lotHeight },
              { x, y: y + lotHeight }
            ],
            etiquetaX: Math.round(x + lotWidth / 2),
            etiquetaY: Math.round(y + lotHeight / 2),
            rotacionEtiqueta: 0,
            ordenCapa: 1,
            visible: true,
            interactivo: true,
            activo: true,
            isAutoGenerated: true
          });
        });

        currentY += rowHeight;
      });

      currentY += stageGap;
    });

    return resultGeometries;
  }

  // Caso Híbrido: ya existen algunas geometrías persistidas
  const unpositionedByBlock = new Map<string, LoteResponse[]>();
  unpositionedLots.forEach((lote) => {
    const blockKey = lote.nombreManzana || lote.codigoManzana || 'Manzana Unica';
    const list = unpositionedByBlock.get(blockKey) ?? [];
    list.push(lote);
    unpositionedByBlock.set(blockKey, list);
  });

  const sortedUnpositionedBlocks = Array.from(unpositionedByBlock.entries()).sort(([a], [b]) =>
    naturalCompare(a, b)
  );

  sortedUnpositionedBlocks.forEach(([blockKey, mLots]) => {
    mLots.sort((lA, lB) => naturalCompare(lA.numero || lA.codigo, lB.numero || lB.codigo));

    const existingGeoms = resultGeometries.filter((g) => {
      const l = lots.find((lot) => lot.idLote === g.idLote);
      const bName = l?.nombreManzana || l?.codigoManzana;
      return bName === blockKey;
    });

    if (existingGeoms.length > 0) {
      const avgY =
        existingGeoms.reduce((sum, g) => sum + (g.etiquetaY ?? 0), 0) / existingGeoms.length;
      let maxX = 0;
      existingGeoms.forEach((g) => {
        g.puntos.forEach((p) => {
          if (p.x > maxX) maxX = p.x;
        });
      });

      const y = Math.round(avgY - lotHeight / 2);
      let nextX = maxX + gapX;

      mLots.forEach((lote) => {
        resultGeometries.push({
          idLoteGeometria: -(lote.idLote),
          idProyecto: lote.idProyecto ?? selectedProjectId ?? 0,
          idPlanoInteractivo: planDetail?.plano.idPlanoInteractivo ?? 0,
          idLote: lote.idLote,
          codigoLote: lote.codigo,
          numeroLote: lote.numero,
          puntos: [
            { x: nextX, y },
            { x: nextX + lotWidth, y },
            { x: nextX + lotWidth, y: y + lotHeight },
            { x: nextX, y: y + lotHeight }
          ],
          etiquetaX: Math.round(nextX + lotWidth / 2),
          etiquetaY: Math.round(y + lotHeight / 2),
          rotacionEtiqueta: 0,
          ordenCapa: 1,
          visible: true,
          interactivo: true,
          activo: true,
          isAutoGenerated: true
        });
        nextX += lotWidth + gapX;
      });
    } else {
      let maxY = 50;
      resultGeometries.forEach((g) => {
        g.puntos.forEach((p) => {
          if (p.y + lotHeight > maxY) maxY = p.y + lotHeight;
        });
      });

      const y = maxY + 25;
      let nextX = 115;

      mLots.forEach((lote) => {
        resultGeometries.push({
          idLoteGeometria: -(lote.idLote),
          idProyecto: lote.idProyecto ?? selectedProjectId ?? 0,
          idPlanoInteractivo: planDetail?.plano.idPlanoInteractivo ?? 0,
          idLote: lote.idLote,
          codigoLote: lote.codigo,
          numeroLote: lote.numero,
          puntos: [
            { x: nextX, y },
            { x: nextX + lotWidth, y },
            { x: nextX + lotWidth, y: y + lotHeight },
            { x: nextX, y: y + lotHeight }
          ],
          etiquetaX: Math.round(nextX + lotWidth / 2),
          etiquetaY: Math.round(y + lotHeight / 2),
          rotacionEtiqueta: 0,
          ordenCapa: 1,
          visible: true,
          interactivo: true,
          activo: true,
          isAutoGenerated: true
        });
        nextX += lotWidth + gapX;
      });
    }
  });

  return resultGeometries;
}

export function LotMap() {
  const { can } = useAuth();
  const navigate = useNavigate();
  const canConfigurePlan = can('lots.configure');
  const [isEditingPlan, setIsEditingPlan] = useState(false);
  const [draftGeometries, setDraftGeometries] = useState<DisplayGeometria[]>([]);
  const [savingPlan, setSavingPlan] = useState(false);

  const [projects, setProjects] = useState<ProyectoResponse[]>([]);
  const [selectedProjectId, setSelectedProjectId] = useState<number | null>(null);
  const [lots, setLots] = useState<LoteResponse[]>([]);
  const [planDetail, setPlanDetail] = useState<PlanoInteractivoDetalleResponse | null>(null);
  const [loadingProjects, setLoadingProjects] = useState(true);
  const [loadingPlan, setLoadingPlan] = useState(false);
  const [selectedLotId, setSelectedLotId] = useState<number | null>(null);
  const [pricesMap, setPricesMap] = useState<Map<number, number>>(new Map());
  const [svgDocument, setSvgDocument] = useState<PlanoSvgDocumento | null>(null);
  const [commercializable, setCommercializable] = useState<Set<number>>(new Set());
  const [viewMode, setViewMode] = useState<'matriz' | 'svg'>('matriz');
  const [layoutMode, setLayoutMode] = useState<'manzanas' | 'general'>('manzanas');
  const [stageFilter, setStageFilter] = useState('all');
  const [blockFilter, setBlockFilter] = useState('all');

  const [query, setQuery] = useState('');
  const [activeStatuses, setActiveStatuses] = useState<string[]>(
    REAL_STATUSES.map((s) => s.code)
  );

  // Cargar proyectos activos al montar
  useEffect(() => {
    let isMounted = true;
    setLoadingProjects(true);
    coreService
      .getActiveProjects()
      .then((res) => {
        if (!isMounted) return;
        setProjects(res);
        if (res.length > 0) {
          setSelectedProjectId(res[0].idProyecto);
        }
      })
      .catch((err: unknown) => {
        if (!isMounted) return;
        const msg = err instanceof ApiError ? err.message : 'Error al cargar proyectos activos';
        toast.error(msg);
      })
      .finally(() => {
        if (isMounted) setLoadingProjects(false);
      });

    return () => {
      isMounted = false;
    };
  }, []);

  const handleLoadLotsResult = (
    result: PromiseSettledResult<LoteResponse[]>
  ): void => {
    if (result.status === 'fulfilled') {
      setLots(result.value);
    } else {
      setLots([]);
      const err = result.reason;
      const msg = err instanceof ApiError ? err.message : 'Error al cargar lotes del proyecto';
      toast.error(msg);
    }
  };

  const handleLoadPricesResult = (
    result: PromiseSettledResult<LotePrecioProyectoItem[]>
  ): void => {
    if (result.status === 'fulfilled') {
      const map = new Map<number, number>();
      result.value.forEach((item) => map.set(item.idLote, item.precio));
      setPricesMap(map);
    } else {
      setPricesMap(new Map());
    }
  };

  const loadProjectData = useCallback((projectId: number, preserveSelection = false) => {
    let isMounted = true;
    setLoadingPlan(true);
    if (!preserveSelection) {
      setSelectedLotId(null);
    }

    Promise.allSettled([
      coreService.searchLots({ idProyecto: projectId, activo: true }),
      coreService.getCurrentPlanDetail(projectId),
      coreService.getProjectLotPrices(projectId),
      projectSvgService.obtener(projectId),
      coreService.getCommercializableLots(projectId)
    ]).then(([lotsResult, planResult, pricesResult, svgResult, commercialResult]) => {
      if (!isMounted) return;
      handleLoadLotsResult(lotsResult);
      if (planResult.status === 'fulfilled') {
        setPlanDetail(planResult.value);
      } else {
        setPlanDetail(null);
      }
      handleLoadPricesResult(pricesResult);
      setSvgDocument(svgResult.status === 'fulfilled' && svgResult.value && svgResult.value.documento
        ? svgResult.value.documento : null);
      setCommercializable(commercialResult.status === 'fulfilled'
        ? new Set(commercialResult.value) : new Set());
      setLoadingPlan(false);
    });

    return () => {
      isMounted = false;
    };
  }, []);

  // Al cambiar de proyecto, cargar datos completos
  useEffect(() => {
    if (!selectedProjectId) {
      setLots([]);
      setPlanDetail(null);
      setPricesMap(new Map());
      setSvgDocument(null);
      setCommercializable(new Set());
      return;
    }
    setViewMode('matriz');
    setStageFilter('all');
    setBlockFilter('all');
    const cleanup = loadProjectData(selectedProjectId, false);
    return cleanup;
  }, [selectedProjectId, loadProjectData]);

  // Refrescar al enfocar la ventana preservando la seleccion del lote
  useEffect(() => {
    const handleFocus = () => {
      if (selectedProjectId) {
        loadProjectData(selectedProjectId, true);
      }
    };
    window.addEventListener('focus', handleFocus);
    return () => {
      window.removeEventListener('focus', handleFocus);
    };
  }, [selectedProjectId, loadProjectData]);

  const currentProject = useMemo(() => {
    return projects.find((p) => p.idProyecto === selectedProjectId) ?? null;
  }, [projects, selectedProjectId]);

  const displayGeometries = useMemo(() => {
    return buildDisplayGeometries(lots, planDetail, selectedProjectId);
  }, [lots, planDetail, selectedProjectId]);

  useEffect(() => {
    if (!isEditingPlan) {
      setDraftGeometries([]);
      return;
    }

    setDraftGeometries(
      displayGeometries.map((geom) => ({
        ...geom,
        puntos: geom.puntos.map((p) => ({ ...p }))
      }))
    );
  }, [isEditingPlan, displayGeometries]);

  const renderedGeometries = isEditingPlan
    ? draftGeometries
    : displayGeometries;

  const handleCancelPlanEditing = () => {
    setDraftGeometries([]);
    setIsEditingPlan(false);
  };

  const handleSavePlan = async () => {
    if (!planDetail?.plano) {
      toast.error(
        'Este proyecto todavía no tiene un plano vigente para guardar la configuración.'
      );
      return;
    }

    const changedGeometries = draftGeometries.filter((draft) => {
      const original = displayGeometries.find(
        (geom) => geom.idLote === draft.idLote
      );

      if (!original) return true;

      return (
        JSON.stringify(draft.puntos) !== JSON.stringify(original.puntos) ||
        draft.etiquetaX !== original.etiquetaX ||
        draft.etiquetaY !== original.etiquetaY ||
        draft.rotacionEtiqueta !== original.rotacionEtiqueta
      );
    });

    if (changedGeometries.length === 0) {
      toast.info('No hay cambios en la distribución del plano.');
      return;
    }

    setSavingPlan(true);

    try {
      await Promise.all(
        changedGeometries.map((geom) =>
          coreService.saveLotGeometry({
            idPlanoInteractivo: planDetail.plano.idPlanoInteractivo,
            idLote: geom.idLote,
            puntos: geom.puntos,
            etiquetaX: geom.etiquetaX ?? null,
            etiquetaY: geom.etiquetaY ?? null,
            rotacionEtiqueta: geom.rotacionEtiqueta ?? 0,
            ordenCapa: geom.ordenCapa ?? 1,
            visible: geom.visible,
            interactivo: geom.interactivo,
            observaciones: geom.observaciones ?? null
          })
        )
      );

      if (selectedProjectId) {
        const refreshedPlan =
          await coreService.getCurrentPlanDetail(selectedProjectId);

        setPlanDetail(refreshedPlan);
      }

      setIsEditingPlan(false);
      setDraftGeometries([]);

      toast.success(
        `${changedGeometries.length} lote(s) actualizados correctamente.`
      );
    } catch (err: unknown) {
      const message =
        err instanceof ApiError
          ? err.message
          : 'No se pudo guardar la configuración del plano.';

      toast.error(message);
    } finally {
      setSavingPlan(false);
    }
  };

  const svgRef = useRef<SVGSVGElement | null>(null);
  const dragStateRef = useRef<DragState | null>(null);

  const clientToSvgPoint = (clientX: number, clientY: number) => {
    const svg = svgRef.current;
    if (!svg) return null;

    const point = svg.createSVGPoint();
    point.x = clientX;
    point.y = clientY;

    const matrix = svg.getScreenCTM();
    if (!matrix) return null;

    return point.matrixTransform(matrix.inverse());
  };

  const handlePointerDown = (
    e: React.PointerEvent<SVGPolygonElement>,
    geom: DisplayGeometria
  ) => {
    if (!isEditingPlan || savingPlan) return;

    e.preventDefault();
    e.stopPropagation();

    setSelectedLotId(geom.idLote);

    const svgPt = clientToSvgPoint(e.clientX, e.clientY);
    if (!svgPt) return;

    dragStateRef.current = {
      idLote: geom.idLote,
      pointerId: e.pointerId,
      startX: svgPt.x,
      startY: svgPt.y,
      originalPoints: geom.puntos.map((p) => ({ ...p })),
      originalEtiquetaX: geom.etiquetaX ?? null,
      originalEtiquetaY: geom.etiquetaY ?? null
    };

    try {
      (e.currentTarget as Element).setPointerCapture(e.pointerId);
    } catch {
      // ignore
    }
  };

  const handlePointerMove = (e: React.PointerEvent<SVGPolygonElement>) => {
    const drag = dragStateRef.current;
    if (!drag || drag.pointerId !== e.pointerId) return;

    const svgPt = clientToSvgPoint(e.clientX, e.clientY);
    if (!svgPt) return;

    const rawDx = svgPt.x - drag.startX;
    const rawDy = svgPt.y - drag.startY;

    let dx = Math.round(rawDx / SNAP_SIZE) * SNAP_SIZE;
    let dy = Math.round(rawDy / SNAP_SIZE) * SNAP_SIZE;

    const limitWidth = planDetail?.plano?.anchoReferencia || canvasDimensions.width;
    const limitHeight = planDetail?.plano?.altoReferencia || canvasDimensions.height;

    const origXValues = drag.originalPoints.map((p) => p.x);
    const origYValues = drag.originalPoints.map((p) => p.y);

    const minOrigX = Math.min(...origXValues);
    const maxOrigX = Math.max(...origXValues);
    const minOrigY = Math.min(...origYValues);
    const maxOrigY = Math.max(...origYValues);

    if (minOrigX + dx < 0) {
      dx = -minOrigX;
    } else if (maxOrigX + dx > limitWidth) {
      dx = limitWidth - maxOrigX;
    }

    if (minOrigY + dy < 0) {
      dy = -minOrigY;
    } else if (maxOrigY + dy > limitHeight) {
      dy = limitHeight - maxOrigY;
    }

    setDraftGeometries((prev) =>
      prev.map((g) => {
        if (g.idLote !== drag.idLote) return g;

        return {
          ...g,
          puntos: drag.originalPoints.map((p) => ({
            x: Math.round(p.x + dx),
            y: Math.round(p.y + dy)
          })),
          etiquetaX:
            drag.originalEtiquetaX != null
              ? Math.round(drag.originalEtiquetaX + dx)
              : null,
          etiquetaY:
            drag.originalEtiquetaY != null
              ? Math.round(drag.originalEtiquetaY + dy)
              : null
        };
      })
    );
  };

  const handlePointerUp = (e: React.PointerEvent<SVGPolygonElement>) => {
    const drag = dragStateRef.current;
    if (drag && drag.pointerId === e.pointerId) {
      try {
        (e.currentTarget as Element).releasePointerCapture(e.pointerId);
      } catch {
        // ignore
      }
      dragStateRef.current = null;
    }
  };

  const { persistedCount, autoCount } = useMemo(() => {
    let p = 0;
    let a = 0;
    displayGeometries.forEach((g) => {
      if (g.isAutoGenerated) {
        a++;
      } else {
        p++;
      }
    });
    return { persistedCount: p, autoCount: a };
  }, [displayGeometries]);

  const canvasDimensions = useMemo(() => {
    let maxX = 920;
    let maxY = 510;

    renderedGeometries.forEach((g) => {
      g.puntos.forEach((p) => {
        if (p.x + 40 > maxX) maxX = Math.ceil(p.x + 40);
        if (p.y + 40 > maxY) maxY = Math.ceil(p.y + 40);
      });
      if (g.etiquetaX != null && g.etiquetaX + 40 > maxX) maxX = Math.ceil(g.etiquetaX + 40);
      if (g.etiquetaY != null && g.etiquetaY + 40 > maxY) maxY = Math.ceil(g.etiquetaY + 40);
    });

    if (planDetail?.plano) {
      if (planDetail.plano.anchoReferencia > maxX) maxX = planDetail.plano.anchoReferencia;
      if (planDetail.plano.altoReferencia > maxY) maxY = planDetail.plano.altoReferencia;
    }

    return {
      width: Math.max(920, maxX),
      height: Math.max(510, maxY)
    };
  }, [renderedGeometries, planDetail]);

  const manzanaLabels = useMemo(() => {
    const rows = new Map<string, number[]>();

    renderedGeometries.forEach((geom) => {
      const lote = lots.find((l) => l.idLote === geom.idLote);
      const manzanaCode = lote?.nombreManzana || lote?.codigoManzana;

      if (!manzanaCode || geom.etiquetaY == null) {
        return;
      }

      const values = rows.get(manzanaCode) ?? [];
      values.push(Number(geom.etiquetaY));
      rows.set(manzanaCode, values);
    });

    return Array.from(rows.entries())
      .map(([codigo, ys]) => ({
        codigo,
        y: ys.reduce((sum, value) => sum + value, 0) / ys.length
      }))
      .sort((a, b) => a.y - b.y);
  }, [renderedGeometries, lots]);

  const planSubtitleText = useMemo(() => {
    if (planDetail?.plano) {
      const v = planDetail.plano.numeroVersion;
      if (autoCount === 0) {
        return `Plano V${v} · ${persistedCount} de ${lots.length} lotes posicionados`;
      }
      return `Plano V${v} · ${persistedCount} configurados · ${autoCount} automáticos`;
    }
    return `Distribución automática · ${lots.length} lotes`;
  }, [planDetail, persistedCount, autoCount, lots.length]);

  const counts = useMemo(() => {
    const acc: Record<string, number> = {
      Total: lots.length,
      DISPONIBLE: 0,
      RESERVADO: 0,
      VENDIDO: 0,
      BLOQUEADO: 0,
      NO_DISPONIBLE: 0
    };

    lots.forEach((l) => {
      const st = l.codigoEstadoLote || 'NO_DISPONIBLE';
      if (acc[st] !== undefined) {
        acc[st]++;
      } else {
        acc.NO_DISPONIBLE++;
      }
    });

    return acc;
  }, [lots]);

  const toggleStatus = (code: string) => {
    setActiveStatuses((prev) =>
      prev.includes(code) ? prev.filter((s) => s !== code) : [...prev, code]
    );
  };

  const stageOptions = useMemo(() => Array.from(new Map(lots
    .filter(l => l.idEtapa != null)
    .map(l => [String(l.idEtapa), l.nombreEtapa || l.codigoEtapa || `Etapa ${l.idEtapa}`])).entries()), [lots]);
  const blockOptions = useMemo(() => Array.from(new Map(lots
    .filter(l => l.idManzana != null && (stageFilter === 'all' || String(l.idEtapa) === stageFilter))
    .map(l => [String(l.idManzana), l.nombreManzana || l.codigoManzana || `Manzana ${l.idManzana}`])).entries()), [lots]);
  const totalArea = useMemo(() => lots.reduce((acc,l) => acc + (Number(l.areaM2) || 0),0),[lots]);
  const allBlocksCount = useMemo(() => new Set(lots.map(l=>l.idManzana).filter(v=>v!=null)).size,[lots]);
  const filteredLotIds = useMemo(() => {
    const q = query.trim().toLowerCase();
    const matches = lots.filter((l) => {
      const matchQuery =
        !q ||
        l.codigo.toLowerCase().includes(q) ||
        (l.numero && l.numero.toLowerCase().includes(q)) ||
        (l.nombreManzana && l.nombreManzana.toLowerCase().includes(q)) ||
        (l.codigoManzana && l.codigoManzana.toLowerCase().includes(q)) ||
        (l.nombreEtapa && l.nombreEtapa.toLowerCase().includes(q));

      const st = l.codigoEstadoLote || 'NO_DISPONIBLE';
      const matchStatus = activeStatuses.includes(st);

      const matchEtapa = stageFilter === 'all' || String(l.idEtapa) === stageFilter;
      const matchManzana = blockFilter === 'all' || String(l.idManzana) === blockFilter;
      return matchQuery && matchStatus && matchEtapa && matchManzana;
    });
    return new Set(matches.map((l) => l.idLote));
  }, [lots, query, activeStatuses, stageFilter, blockFilter]);

  const selectedLot = useMemo(() => {
    if (selectedLotId === null) return null;
    return lots.find((l) => l.idLote === selectedLotId) ?? null;
  }, [lots, selectedLotId]);
  const canOperate = Boolean(selectedLot && can('sales.create') && selectedLot.activo
    && selectedLot.codigoEstadoLote === 'DISPONIBLE' && pricesMap.has(selectedLot.idLote)
    && commercializable.has(selectedLot.idLote));
  const openCommercialFlow = (operacion: 'Separacion' | 'Venta') => {
    if(!selectedLot || !canOperate || !selectedLot.idEtapa || !selectedProjectId) return;
    const params = new URLSearchParams({
      origen: 'plano', operacion, idProyecto: String(selectedProjectId),
      idEtapa: String(selectedLot.idEtapa), idLote: String(selectedLot.idLote)
    });
    navigate(`/ventas?${params.toString()}`);
  };

  if (loadingProjects) {
    return (
      <div className="flex h-64 items-center justify-center">
        <p className="text-brand-500 text-sm">Cargando proyectos...</p>
      </div>
    );
  }

  if (projects.length === 0) {
    return (
      <div>
        <PageHeader
          title="Plano interactivo"
          description="Consulta la disponibilidad del inventario por etapa y manzana. Selecciona un lote para ver su información comercial."
          meta={
            currentProject ? (
              <>
                <Badge tone="brand">{currentProject.nombre}</Badge>
                <span className="text-[12px] text-brand-400">
                  {number(lots.length)} lotes ·{' '}
                  {currentProject.distrito ||
                    currentProject.provincia ||
                    'Ubicación n/d'}
                </span>
              </>
            ) : undefined
          }
          actions={
            canConfigurePlan ? (
              isEditingPlan ? (
                <div className="flex items-center gap-2">
                  <Button
                    icon={XIcon}
                    onClick={handleCancelPlanEditing}
                    disabled={savingPlan}
                    className="border-brand-200 text-brand-700 hover:bg-brand-50"
                  >
                    Cancelar
                  </Button>

                  <Button
                    icon={SaveIcon}
                    onClick={handleSavePlan}
                    disabled={savingPlan}
                    className="bg-brand-900 text-white hover:bg-brand-800"
                  >
                    {savingPlan ? 'Guardando...' : 'Guardar cambios'}
                  </Button>
                </div>
              ) : (
                <Button
                  icon={Settings2Icon}
                  onClick={() => setIsEditingPlan(true)}
                  className="border-brand-200 text-brand-800 hover:bg-brand-50"
                >
                  Configurar plano
                </Button>
              )
            ) : undefined
          }
        />
      </div>
    );
  }


  return (
    <div className="space-y-5">
      <PageHeader title="Plano interactivo"
        description="Explora el inventario por manzana, consulta la ficha de cada lote y visualiza el plano SVG del proyecto."
        actions={canConfigurePlan ? (isEditingPlan
          ? <div className="flex items-center gap-2">
              <Button icon={XIcon} onClick={handleCancelPlanEditing} disabled={savingPlan}>Cancelar</Button>
              <Button icon={SaveIcon} variant="primary" onClick={()=>void handleSavePlan()}
                disabled={savingPlan}>{savingPlan?'Guardando…':'Guardar posiciones'}</Button>
            </div>
          : <Button icon={Settings2Icon} onClick={()=>{setViewMode('matriz');setIsEditingPlan(true);}}>
              Configurar posiciones
            </Button>) : undefined}/>
      {currentProject && <section className="overflow-hidden rounded-2xl border border-brand-200 bg-white p-4 shadow-sm lg:p-5">
        <div className="grid gap-5 lg:grid-cols-[minmax(0,1fr)_minmax(240px,1.1fr)_180px] lg:items-center">
          <div>
            <p className="text-[11px] font-bold uppercase tracking-[0.12em] text-brand-400">Proyecto</p>
            <h2 className="mt-1 text-2xl font-bold tracking-tight text-brand-900">{currentProject.nombre}</h2>
            <p className="mt-2 flex items-center gap-1.5 text-sm text-brand-500">
              <MapPinIcon className="h-4 w-4 shrink-0 text-emerald-600"/>
              {[currentProject.distrito,currentProject.provincia].filter(Boolean).join(', ') ||
                currentProject.ubicacionReferencia || 'Ubicación sin especificar'}
            </p>
            <div className="mt-4 flex flex-wrap gap-2">
              <span className="rounded-lg border border-brand-200 bg-brand-50 px-3 py-2 text-xs font-semibold text-brand-800">{allBlocksCount} manzanas</span>
              <span className="rounded-lg border border-brand-200 bg-brand-50 px-3 py-2 text-xs font-semibold text-brand-800">{number(lots.length)} lotes</span>
              <span className="rounded-lg border border-brand-200 bg-brand-50 px-3 py-2 text-xs font-semibold text-brand-800">{fmtArea(totalArea)} de lotes</span>
            </div>
            <div className="mt-4">
              <label className="mb-1 block text-[11px] font-semibold text-brand-500" htmlFor="plano-proyecto">Cambiar proyecto</label>
              <Select id="plano-proyecto" value={selectedProjectId??''}
                onChange={e=>setSelectedProjectId(Number(e.target.value))}
                disabled={isEditingPlan || savingPlan} className="w-full max-w-xs">
                {projects.map(p=><option key={p.idProyecto} value={p.idProyecto}>{p.nombre}</option>)}
              </Select>
            </div>
          </div>
          <div className="h-44 overflow-hidden rounded-xl border border-brand-100 bg-brand-50/70">
            {svgDocument ? <PlanSvgShapes documento={svgDocument} lotes={lots} seleccionado={selectedLotId} miniatura/>
              : <svg viewBox={`0 0 ${canvasDimensions.width} ${canvasDimensions.height}`} preserveAspectRatio="xMidYMid meet"
                  className="h-full w-full" role="img" aria-label="Vista previa automática del inventario del proyecto">
                  <rect width={canvasDimensions.width} height={canvasDimensions.height} rx="18" fill="#eef5f8"/>
                  {displayGeometries.map(g=>{
                    const lote=lots.find(l=>l.idLote===g.idLote);
                    return <polygon key={g.idLote} points={g.puntos.map(p=>`${p.x},${p.y}`).join(' ')}
                      fill={selectedLotId===g.idLote ? '#2563eb' : getPolygonColors(lote?.codigoEstadoLote).fill}
                      stroke="#ffffff" strokeWidth="3"/>;
                  })}
                </svg>}
          </div>
          <div className="flex flex-col items-start gap-3 lg:items-center lg:text-center">
            <FileImageIcon className="h-8 w-8 text-emerald-600"/>
            <div><p className="text-sm font-bold text-brand-900">Plano del proyecto</p>
              <p className="mt-1 text-xs text-brand-500">{svgDocument ? svgDocument.nombreArchivo : 'DWG original o SVG interactivo'}</p></div>
            <Button size="sm" onClick={()=>{setViewMode('svg');if(isEditingPlan)handleCancelPlanEditing();}}>
              {svgDocument?'Ver plano SVG':'Importar DWG / SVG'}
            </Button>
          </div>
        </div>
      </section>}
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div className="inline-flex rounded-xl border border-brand-200 bg-white p-1 shadow-sm" role="tablist" aria-label="Vista del plano">
          <button type="button" role="tab" aria-selected={viewMode==='matriz'} onClick={()=>setViewMode('matriz')}
            className={cn('inline-flex items-center gap-2 rounded-lg px-4 py-2 text-sm font-semibold',
              viewMode==='matriz'?'bg-brand-900 text-white':'text-brand-600 hover:bg-brand-50')}>
            <Grid2X2Icon className="h-4 w-4"/> Matriz
          </button>
          <button type="button" role="tab" aria-selected={viewMode==='svg'}
            onClick={()=>{if(isEditingPlan)handleCancelPlanEditing();setViewMode('svg');}}
            className={cn('inline-flex items-center gap-2 rounded-lg px-4 py-2 text-sm font-semibold',
              viewMode==='svg'?'bg-brand-900 text-white':'text-brand-600 hover:bg-brand-50')}>
            <MapIcon className="h-4 w-4"/> Plano SVG
          </button>
        </div>
        <div className="flex flex-wrap items-center gap-2">
          <Select aria-label="Filtrar por etapa" value={stageFilter}
            onChange={e=>{setStageFilter(e.target.value);setBlockFilter('all');}}
            className="w-48">
            <option value="all">Todas las etapas</option>
            {stageOptions.map(([id,nombre])=><option key={id} value={id}>{nombre}</option>)}
          </Select>
          <Select aria-label="Filtrar por manzana" value={blockFilter}
            onChange={e=>setBlockFilter(e.target.value)} className="w-48">
            <option value="all">Todas las manzanas</option>
            {blockOptions.map(([id,nombre])=><option key={id} value={id}>{nombre}</option>)}
          </Select>
        </div>
      </div>
      <div className="grid grid-cols-1 items-start gap-4 xl:grid-cols-[minmax(0,1fr)_350px]">
        <Card className="min-w-0 overflow-hidden rounded-2xl shadow-sm">
          {viewMode==='matriz' ? <>
            <div className="flex flex-wrap items-center justify-between gap-3 px-5 pb-1 pt-5">
              <div className="flex items-center gap-3">
                <div className="rounded-xl bg-emerald-50 p-2.5"><MapIcon className="h-5 w-5 text-emerald-700"/></div>
                <div><h3 className="text-lg font-bold text-brand-900">Mapa de Lotes</h3>
                  <p className="text-xs text-brand-500">Selecciona un lote para consultar su ficha</p></div>
              </div>
              <div className="inline-flex rounded-lg border border-brand-200 bg-white p-1 text-xs font-semibold">
                <button type="button" onClick={()=>setLayoutMode('manzanas')}
                  className={cn('rounded-md px-3 py-2',layoutMode==='manzanas'?'bg-brand-900 text-white':'text-brand-500')}>
                  Vista por manzanas
                </button>
                <button type="button" onClick={()=>setLayoutMode('general')}
                  className={cn('rounded-md px-3 py-2',layoutMode==='general'?'bg-brand-900 text-white':'text-brand-500')}>
                  Vista general
                </button>
              </div>
            </div>
            <div className="flex flex-wrap items-center gap-3 border-b border-brand-100 px-5 py-3">
              <SearchInput value={query} onValueChange={setQuery}
                placeholder="Buscar lote, manzana o etapa..." label="Buscar lote"
                className="w-full sm:max-w-xs"/>
              <span className="ml-auto text-xs font-medium text-brand-500">{planSubtitleText}</span>
            </div>
            <div className="p-4">
              {loadingPlan ? <div className="p-20 text-center text-sm text-brand-500">Cargando lotes…</div>
                : lots.length===0 ? <EmptyState title="Proyecto sin lotes" description="Registra lotes antes de visualizar el plano." icon={MapPinIcon}/>
                : <div className="space-y-3">
                  {isEditingPlan && <div className="rounded-lg border border-amber-200 bg-amber-50 p-3 text-xs font-medium text-amber-900">
                    Modo configuración: arrastra los lotes para cambiar su posición. Ajuste a cuadrícula: 10.
                  </div>}
                  <div className="overflow-auto rounded-xl border border-brand-100 bg-[#f2f6fa] p-2 sm:p-3">
                  <svg
                    ref={svgRef}
                    style={{ touchAction: 'none' }}
                    viewBox={`0 0 ${canvasDimensions.width} ${canvasDimensions.height}`}
                    preserveAspectRatio="xMidYMid meet"
                    className="w-full h-auto min-h-[450px] max-h-[740px] select-none"
                  >
                    <defs>
                      <filter
                        id="lot-shadow"
                        x="-20%"
                        y="-20%"
                        width="140%"
                        height="140%"
                      >
                        <feDropShadow
                          dx="0"
                          dy="2"
                          stdDeviation="2"
                          floodColor="#0f172a"
                          floodOpacity="0.12"
                        />
                      </filter>

                      <pattern
                        id="editor-grid"
                        width="20"
                        height="20"
                        patternUnits="userSpaceOnUse"
                      >
                        <path
                          d="M 20 0 L 0 0 0 20"
                          fill="none"
                          stroke="#cbd5e1"
                          strokeWidth="0.6"
                        />
                      </pattern>
                    </defs>

                    {/* Fondo suave */}
                    <rect
                      x="0"
                      y="0"
                      width={canvasDimensions.width}
                      height={canvasDimensions.height}
                      rx="18"
                      fill={isEditingPlan ? 'url(#editor-grid)' : '#f1f5f9'}
                    />

                    {/* Línea horizontal de separación entre bloques de manzanas si aplica */}
                    <line
                      x1="100"
                      y1="275"
                      x2={canvasDimensions.width - 20}
                      y2="275"
                      stroke="#e2e8f0"
                      strokeWidth="1"
                      strokeDasharray="6 6"
                    />

                    {/* Leyendas de manzanas a la izquierda */}
                    {layoutMode === 'manzanas' && manzanaLabels.map((row) => (
                      <g key={row.codigo}>
                        <rect
                          x="12"
                          y={row.y - 19}
                          width="94"
                          height="38"
                          rx="11"
                          fill="#e7f5f1"
                          stroke="#c6e5df"
                          strokeWidth="1.5"
                        />

                        <text
                          x="59"
                          y={row.y}
                          textAnchor="middle"
                          dominantBaseline="central"
                          fontSize="11"
                          fontWeight="700"
                          fill="#334155"
                          pointerEvents="none"
                        >
                          {row.codigo}
                        </text>
                      </g>
                    ))}

                    {/* Lotes */}
                    {renderedGeometries.map((geom: DisplayGeometria) => {
                      const lote = lots.find((l) => l.idLote === geom.idLote);
                      const isMatch = filteredLotIds.has(geom.idLote);
                      const isSelected = selectedLotId === geom.idLote;
                      const colors = getPolygonColors(lote?.codigoEstadoLote);

                      const pointsStr = geom.puntos.map((p) => `${p.x},${p.y}`).join(' ');

                      return (
                        <g key={geom.idLoteGeometria} className="cursor-pointer">
                          <polygon
                            points={pointsStr}
                            fill={isSelected ? '#2563eb' : colors.fill}
                            stroke={isSelected ? '#1d4ed8' : colors.stroke}
                            strokeWidth={isSelected ? 3.5 : 1.5}
                            strokeLinejoin="round"
                            filter="url(#lot-shadow)"
                            opacity={isMatch ? (isSelected ? 1 : 0.9) : 0.18}
                            className={cn(
                              'transition-all duration-150 hover:brightness-105',
                              isEditingPlan ? 'cursor-grab active:cursor-grabbing' : 'cursor-pointer'
                            )}
                            onClick={() => setSelectedLotId(geom.idLote)}
                            onPointerDown={(e) => handlePointerDown(e, geom)}
                            onPointerMove={handlePointerMove}
                            onPointerUp={handlePointerUp}
                            onPointerCancel={handlePointerUp}
                          >
                            <title>
                              {geom.codigoLote} - {lote?.nombreEstadoLote || lote?.codigoEstadoLote || 'Sin estado'}
                            </title>
                          </polygon>

                          {geom.etiquetaX != null && geom.etiquetaY != null && (
                            <text
                              x={geom.etiquetaX}
                              y={geom.etiquetaY}
                              transform={
                                geom.rotacionEtiqueta
                                  ? `rotate(${geom.rotacionEtiqueta}, ${geom.etiquetaX}, ${geom.etiquetaY})`
                                  : undefined
                              }
                              textAnchor="middle"
                              dominantBaseline="central"
                              fontSize="12"
                              fontWeight="700"
                              fill="#ffffff"
                              pointerEvents="none"
                              opacity={isMatch ? 1 : 0.3}
                            >
                              {geom.codigoLote}
                            </text>
                          )}
                        </g>
                      );
                    })}
                  </svg>
                  </div>
                </div>}
            </div>
          </> : <div className="p-4 sm:p-5">
            {selectedProjectId && <ProjectSvgPanel key={selectedProjectId} proyecto={selectedProjectId}
              lotes={lots} documento={svgDocument} onSave={setSvgDocument}
              seleccionado={selectedLotId} onSelect={setSelectedLotId} puedeConfigurar={canConfigurePlan}/>}
          </div>}
          <div className="flex flex-wrap items-center gap-2 border-t border-brand-100 px-4 py-3">
            <span className="text-xs font-bold text-brand-800">Leyenda:</span>
            {REAL_STATUSES.map(st=>{
              const checked=activeStatuses.includes(st.code);
              return <button key={st.code} type="button" aria-pressed={checked}
                onClick={()=>toggleStatus(st.code)}
                className={cn('inline-flex items-center gap-1 rounded-full px-2 py-1 text-[11px] font-medium',
                  checked?'bg-brand-50 text-brand-700':'bg-white text-brand-300 line-through')}>
                <span className={cn('h-2.5 w-2.5 rounded-[3px]',st.dotColor)}/>{st.label}
                <span className="text-brand-400">{counts[st.code]??0}</span>
              </button>;
            })}
            <span className="inline-flex items-center gap-1 rounded-full bg-blue-50 px-2 py-1 text-[11px] text-blue-800">
              <span className="h-2.5 w-2.5 rounded-[2px] border border-blue-700 bg-blue-500"/>Seleccionado
            </span>
            <span className="ml-auto text-xs font-bold text-brand-900">Total: {lots.length} lotes</span>
          </div>
        </Card>
        <LotMapDetailCard lote={selectedLot} precio={selectedLot?pricesMap.get(selectedLot.idLote)??null:null}
          puedeOperar={canOperate} onSeparar={()=>openCommercialFlow('Separacion')}
          onVender={()=>openCommercialFlow('Venta')}/>
      </div>
    </div>
  );
}
