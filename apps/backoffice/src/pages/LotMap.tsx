function getPolygonColors(codigoEstadoLote?: string | null) {
  const found = REAL_STATUSES.find((s) => s.code === codigoEstadoLote);
  if (found) {
    return { fill: found.polygonFill, stroke: found.polygonStroke };
  }
  return { fill: '#9ca3af', stroke: '#4b5563' };
}

function naturalCompare(a?: string | null, b?: string | null): number {
  const strA = (a ?? '').trim();
  const strB = (b ?? '').trim();
  return strA.localeCompare(strB, undefined, { numeric: true, sensitivity: 'base' });
}

function buildDisplayGeometries(
  lots: LoteResponse[],
  planDetail: PlanoInteractivoDetalleResponse | null,
  selectedProjectId: number | null
): DisplayGeometria[] {
  if (lots.length === 0) return [];

  const persistedMap = new Map<number, LoteGeometriaResponse>();
  for (const g of planDetail?.lotes ?? []) {
    if (g.activo && g.puntos.length >= 3) persistedMap.set(g.idLote,g);
  }
  const result:DisplayGeometria[]=[];
  const missing=new Map<string,LoteResponse[]>();
  const blockKey=(l:LoteResponse)=>String(l.idManzana??l.codigoManzana??l.nombreManzana??'sin-manzana');
  const byId=new Map(lots.map(l=>[l.idLote,l]));
  for(const lot of lots){
    const persisted=persistedMap.get(lot.idLote);
    if(persisted)result.push({...persisted,codigoLote:lot.codigo,numeroLote:lot.numero,isAutoGenerated:false});
    else {const key=blockKey(lot),group=missing.get(key)??[];group.push(lot);missing.set(key,group);}
  }
  const groups=[...missing.entries()].sort(([,a],[,b])=>naturalCompare(a[0].codigoManzana??a[0].nombreManzana,b[0].codigoManzana??b[0].nombreManzana));
  for(const [key,group] of groups){
    group.sort((a,b)=>naturalCompare(a.numero??a.codigo,b.numero??b.codigo));
    const existing=result.filter(g=>{const lot=byId.get(g.idLote);return lot&&blockKey(lot)===key;});
    const y=existing.length?Math.max(20,Math.round(bounds(existing[0].puntos).top)):
      Math.max(40,...result.map(g=>bounds(g.puntos).bottom+25));
    let x=existing.length?Math.max(...existing.map(g=>bounds(g.puntos).right))+12:120;
    for(const lot of group){
      let points=rectangle(x,y,68,55);
      while(result.some(g=>overlaps(g.puntos,points))){x+=80;points=rectangle(x,y,68,55);}
      result.push({idLoteGeometria:-lot.idLote,idProyecto:lot.idProyecto??selectedProjectId??0,
        idPlanoInteractivo:planDetail?.plano.idPlanoInteractivo??0,idLote:lot.idLote,codigoLote:lot.codigo,
        numeroLote:lot.numero,puntos:points,etiquetaX:x+34,etiquetaY:y+27.5,rotacionEtiqueta:0,
        ordenCapa:1,visible:true,interactivo:true,activo:true,isAutoGenerated:true});
      x+=80;
    }
  }
  return result;
}

