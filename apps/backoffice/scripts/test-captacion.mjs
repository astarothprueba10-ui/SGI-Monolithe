import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { transformSync } from 'esbuild';
import { webcrypto } from 'node:crypto';
if (!globalThis.crypto) Object.defineProperty(globalThis, 'crypto', { value: webcrypto });
const load = async source => import(`data:text/javascript;base64,${Buffer.from(transformSync(source, { loader: 'ts', format: 'esm' }).code).toString('base64')}`);
const backend = readFileSync(new URL('../src/lib/captacion.ts', import.meta.url), 'utf8');
const publico = readFileSync(new URL('../../pagina-web/src/lib/captacion.ts', import.meta.url), 'utf8');
assert.equal(backend, publico, 'Los dos formularios deben usar las mismas reglas');
const { validarCaptacion, normalizarCaptacion, IdentidadEnvio } = await load(backend);
const valido = { nombres: 'Ana', apellidoPaterno: 'Pérez', correo: 'ANA+LEAD@EJEMPLO.COM', telefono: '+51 (987) 654-321', idProyecto: 1, motivoContacto: 'Comprar lote' };
assert.deepEqual(validarCaptacion(valido), {});
assert.equal(normalizarCaptacion(valido).correo, 'ana+lead@ejemplo.com');
assert.equal(normalizarCaptacion(valido).telefono, '+51987654321');
for (const key of ['nombres','apellidoPaterno','correo','telefono','motivoContacto']) assert.ok(validarCaptacion({ ...valido, [key]: '' })[key]);
for (const telefono of ['++51987654321', '+0000000', '123', '1234567 ext 1', '9'.repeat(16)]) assert.ok(validarCaptacion({ ...valido, telefono }).telefono);
assert.ok(validarCaptacion({ ...valido, idProyecto: 0 }).idProyecto);
assert.ok(validarCaptacion({ ...valido, mensaje: 'x'.repeat(4001) }).mensaje);
assert.ok(validarCaptacion({ ...valido, tipoDocumento: 'DNI', numeroDocumento: '1234567' }).numeroDocumento);
assert.deepEqual(validarCaptacion({ ...valido, tipoDocumento: 'DNI', numeroDocumento: '12345678' }), {});
assert.ok(validarCaptacion({ ...valido, tipoDocumento: 'DNI' }).numeroDocumento);
const identity = new IdentidadEnvio(); const id = identity.para(normalizarCaptacion(valido));
assert.equal(identity.para(normalizarCaptacion({ ...valido, correo: 'ana+lead@ejemplo.com' })), id);
assert.notEqual(identity.para(normalizarCaptacion({ ...valido, idProyecto: 2 })), id);
identity.reiniciar(); assert.notEqual(identity.para(normalizarCaptacion(valido)), id);
const api = readFileSync(new URL('../../pagina-web/src/services/api.ts', import.meta.url), 'utf8');
const start = api.indexOf('export async function enviarConsulta('), end = api.indexOf('/**\n * Obtiene el catálogo', start);
const { enviarConsulta } = await load(`const API_BASE_URL = 'http://test';\n${api.slice(start,end)}`);
let calls = 0;
globalThis.fetch = async () => { calls++; return { ok: false, json: async () => ({ message: 'Proyecto inactivo' }) }; };
await assert.rejects(enviarConsulta(valido), /Proyecto inactivo/); assert.equal(calls, 1);
globalThis.fetch = async () => { throw new Error('Sin conexión'); };
await assert.rejects(enviarConsulta(valido), /Sin conexión/);
globalThis.fetch = async () => ({ ok: true, json: async () => ({}) });
await assert.rejects(enviarConsulta(valido), /confirmación válida/);
globalThis.fetch = async () => ({ ok: true, json: async () => ({ idConsulta: 12, codigo: 'MON-000012' }) });
assert.equal((await enviarConsulta(valido)).codigo, 'MON-000012');
console.log('Validaciones comunes, reintentos y confirmación real del registro: OK');

const catalogSource = api.slice(api.indexOf('export interface ProyectoCaptacion'));
const { obtenerProyectosCaptacion } = await load(`const API_BASE_URL = 'http://test';\n${catalogSource}`);
const urls = [];
globalThis.fetch = async url => {
  urls.push(url);
  const page = url.endsWith('despues=0') ? Array.from({ length: 200 }, (_, i) => ({ idProyecto: i + 1, nombre: `Proyecto ${i + 1}` })) : [{ idProyecto: 201, nombre: 'Proyecto final' }];
  return { ok: true, json: async () => page };
};
assert.equal((await obtenerProyectosCaptacion()).length, 201);
assert.equal(urls.length, 2);
assert.ok(urls.every(u => u.includes('/api/public/captacion/proyectos?')));
assert.ok(urls[1].endsWith('despues=200'));
globalThis.fetch = async () => ({ ok: true, json: async () => [] });
assert.deepEqual(await obtenerProyectosCaptacion(), []);
globalThis.fetch = async () => ({ ok: false });
await assert.rejects(obtenerProyectosCaptacion(), /No se pudo cargar/);
globalThis.fetch = async () => ({ ok: true, json: async () => [{ idProyecto: 0, nombre: 'Inválido' }] });
await assert.rejects(obtenerProyectosCaptacion(), /respuesta inválida/);
assert.deepEqual(validarCaptacion({ ...valido, apellidoPaterno: 'De la Cruz Flores' }), {});
console.log('Catálogo de captación: paginación, vacío, error y respuesta inválida: OK');

